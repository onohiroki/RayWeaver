package clispec

// Asphere is the flag surface of `rayweave asphere`.
var Asphere = Spec{Command: "asphere", Flags: []Flag{
	{Name: "config", Kind: String, Role: RoleSelector,
		Help: "select config by id (multi-config mode)"},
	{Name: "glass-dir", Kind: String, Role: RoleSetting,
		Help: "AGF glass catalog directory"},
	{Name: "rings", Kind: Int, Role: RoleSetting,
		Help: "polar cell radial rings (default 8)"},
	{Name: "angles", Kind: Int, Role: RoleSetting,
		Help: "polar cell angular sectors (default 16)"},
	{Name: "t-bins", Kind: Int, Role: RoleSetting,
		Help: "beam-frame tangential bins (default 8)"},
	{Name: "pupil-samples", Kind: Int, Role: RoleSetting,
		Help: "pupil grid radial samples (default 21)"},
	{Name: "sensitivity-samples", Kind: Int, Default: -1, Role: RoleSetting,
		Help: "sensitivity trace radial samples (default 9; 0 = disable, use analytic proxy)"},
	{Name: "top-k", Kind: Int, Role: RoleSetting,
		Help: "number of top-ranked surfaces to fit (default 3)"},
	{Name: "sag-scale", Kind: Float, Role: RoleSetting,
		Help: "initial sag scale alpha (default 0.2)"},
	{Name: "calibrate-scale", Kind: BoolString, Role: RoleSetting,
		Help: "derive each candidate's embedded asphere scale from the measured ray-trace response (default: on; true|false)"},
	{Name: "scale-probes", Kind: String, Role: RoleSetting,
		Help: "comma-separated scales to verify instead of the quadratic estimate (e.g. 0.1,0.25,0.5,1.0)"},
	{Name: "validate", Kind: Bool, Role: RoleAction,
		Help: "run a short DLS per fitted surface to verify the asphere improves the merit"},
	{Name: "apply", Kind: Bool, Role: RoleAction,
		Help: "insert the top-ranked DLS-validated asphere onto its surface (implies --validate)"},
	{Name: "dls-iter", Kind: Int, Default: 20, Role: RoleSetting,
		Help: "DLS iterations per validated surface (with --validate)"},
	{Name: "num-rays", Kind: Int, Role: RoleSetting,
		Help: "pupil grid rays for the validation DLS (default 64)"},
	{Name: "diagnostics", Kind: String, Role: RoleSetting,
		Help: "comma-separated diagnostics to emit: opd, focus (empty = no extra data)"},
	{Name: "focus-samples", Kind: Int, Role: RoleSetting,
		Help: "rays per T/S fan for the focus channel (default 17)"},
	{Name: "focus-fans", Kind: String, Role: RoleSetting,
		Help: "comma-separated focus channel fans: tangential,sagittal (default both)"},
}}
