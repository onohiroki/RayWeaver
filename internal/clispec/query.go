package clispec

// Query is the flag surface of `rayweave query`.
var Query = Spec{Command: "query", Flags: []Flag{
	{Name: "yaml", Kind: Bool, Role: RoleOutput,
		Help: "output the result as YAML"},
	{Name: "json", Kind: Bool, Role: RoleOutput,
		Help: "output the result as JSON"},
	{Name: "csv", Kind: String, Role: RoleOutput,
		Help: "CSV output: iterate PATH and emit one row per element (PATH[:col1,col2,...])"},
	{Name: "csv-header", Kind: Bool, Role: RoleOutput,
		Help: "with --csv, emit a header row with the column names"},
	{Name: "csv-keep-all", Kind: Bool, Role: RoleOutput,
		Help: "with --csv, keep rows where a column is missing/null (emit empty cells)"},
	{Name: "each", Kind: String, Role: RoleOutput,
		Help: "iterate PATH and print one row per element (PATH[:col1,col2,...])"},
	{Name: "count", Kind: String, Role: RoleOutput,
		Help: "count non-null values resolved by PATH"},
	{Name: "len", Kind: String, Role: RoleOutput,
		Help: "length of the array/mapping resolved by PATH"},
	{Name: "sum", Kind: String, Role: RoleOutput,
		Help: "sum of the numeric values resolved by PATH"},
	{Name: "product", Kind: String, Role: RoleOutput,
		Help: "product of the numeric values resolved by PATH"},
	{Name: "stdev", Kind: String, Role: RoleOutput,
		Help: "population standard deviation of the numeric values resolved by PATH"},
	{Name: "jsonl", Kind: Bool, Role: RoleSetting,
		Help: "read JSON Lines instead of a single YAML document (optimize/escape --log output)"},
	{Name: "where", Kind: String, Role: RoleSetting,
		Help: "with --jsonl, keep only lines where EXPR is truthy"},
	{Name: "first", Kind: Bool, Role: RoleSetting,
		Help: "with --jsonl, use the first matching line instead of the last"},
	{Name: "gate", Kind: String, Role: RoleOutput,
		Help: "evaluate EXPR, print a pass record and exit 0/1 by truthiness"},
	{Name: "printf", Kind: String, Role: RoleOutput,
		Help: "Go fmt format string applied to the output value(s)"},
	{Name: "default", Kind: String, Default: "-1", Role: RoleOutput,
		Help: "value printed when a scalar result is missing/null (default -1)"},
	{Name: "default-num", Kind: String, Role: RoleOutput,
		Help: "numeric default for missing/null --each column values (e.g. NaN, 0, -1)"},
	{Name: "printf-nan-empty", Kind: Bool, Role: RoleOutput,
		Help: "with --printf, replace NaN values with width-matched spaces"},
	{Name: "expr", Kind: String, Role: RoleSetting,
		Help: "expression to evaluate (same as the positional SELECTOR)"},
	{Name: "edit", Kind: StringList, Role: RoleSetting, Repeat: true,
		Help: "mutation expression (repeatable, applied in order); supports =, +=, -=, |=, del PATH"},
	{Name: "set", Kind: StringList, Role: RoleSetting, Repeat: true,
		Help: "bind VAR=EXPR (repeatable, evaluated in order; later bindings may reference earlier ones)"},
	{Name: "raw", Short: "r", Kind: Bool, Role: RoleOutput,
		Help: "raw text output (the default for scalars; accepted for clarity)"},
}}
